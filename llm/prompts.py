def build_user_prompt(event: GuidanceEvent, context: dict | None = None) -> str:
    """이벤트 + 부가 정보(시간, 시간대, 복용 이력 등)를 user 프롬프트로 조립.

    지시문 안의 {meal_label}, {next_slot_label} 자리는 코드가 실제 값으로 직접
    채운다 — 소형 모델에게 시간대 치환을 맡기면 예시를 그대로 베끼는 문제가
    있어서(점심→저녁 오류), 지시문 자체가 정답을 담도록 하는 설계다.
    """
    prompt = EVENT_CONTEXT[event]
    ctx = context or {}
    prompt = prompt.replace("{meal_label}", ctx.get("meal_label") or "정해진")
    prompt = prompt.replace("{next_slot_label}", ctx.get("next_slot_label") or "정해진")

    if context:
        extras = []
        if "time" in context:
            extras.append(f"현재 시각: {context['time']}")
        if "meal_label" in context:
            extras.append(f"시간대: {context['meal_label']}")
        if "slot_ends_at" in context:
            extras.append(f"시간대 종료 시각: {context['slot_ends_at']} (내부 참고용)")
        if "next_slot_label" in context:
            line = f"다음 복약 시간대: {context['next_slot_label']}"
            if "next_slot_starts_at" in context:
                line += f" ({context['next_slot_starts_at']} 시작)"
            extras.append(line)
        if "last_medication_time" in context:
            extras.append(f"마지막 복용 시각: {context['last_medication_time']}")
        if "bite_count" in context:
            extras.append(
                f"이번 식사에서 확인된 섭취 횟수: {context['bite_count']}회"
                " (내부 참고용 — 문장에 숫자를 넣지 마세요)"
            )
        if "drink_count" in context:
            extras.append(
                f"이번 식사에서 확인된 음수 횟수: {context['drink_count']}회"
                " (내부 참고용 — 문장에 숫자를 넣지 마세요)"
            )
        if "patient_name" in context:
            extras.append(f"환자 호칭: {context['patient_name']}")
        if extras:
            prompt += "\n\n[참고 정보]\n" + "\n".join(extras)

    return prompt


